import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { copyFile, lstat, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const args = process.argv.slice(2);
if (args.includes('--help')) {
  console.log('Usage: node scripts/dsh-distribution.mjs [--output <directory>]\nPrepare the built DSH plugin for commit-pinned Git distribution. Run npm run dsh:build first.');
  process.exit(0);
}
if (args.length !== 0 && (args.length !== 2 || args[0] !== '--output' || !args[1])) {
  throw new Error('Expected no arguments or --output <directory>.');
}

const output = resolve(root, args[1] ?? '.tools/dsh-publication/distribution');
const packagePath = 'plugins/deepseek-specflow';
const source = join(root, packagePath);
const target = join(output, packagePath);
const sourceRelative = relative(source, target);
if (!sourceRelative || (!isAbsolute(sourceRelative) && sourceRelative.split(/[\\/]/)[0] !== '..')) {
  throw new Error('The distribution directory must be outside the plugin source directory.');
}

const runtimeFiles = [
  'README.md', 'THIRD_PARTY_NOTICES.md', 'cordis.patch.yml',
  'dist/index.mjs', 'dist/client.js', 'dist/ZOD_LICENSE', 'dist/build-info.json',
];
const permitted = new Set(['package.json', 'LICENSE', ...runtimeFiles]);
const manifest = JSON.parse(await readFile(join(source, 'package.json'), 'utf8'));
assert.equal(manifest.name, 'dsh-plugin-specflow');
assert.equal(manifest.dsh?.bundle?.patch, './cordis.patch.yml');
assert.ok(manifest.engines?.dsh && manifest.engines?.node, 'The package must declare its DSH and Node compatibility.');
assert.ok(!manifest.dependencies?.specflow, 'Git distribution cannot depend on the desktop checkout.');

// A Git dependency's lifecycle runs in its fetched tree. The source scripts need
// the monorepo build tools, while this distribution already contains their output.
delete manifest.scripts;
delete manifest.devDependencies;

const build = JSON.parse(await readFile(join(source, 'dist/build-info.json'), 'utf8'));
assert.equal(build.name, manifest.name);
assert.equal(build.version, manifest.version);
assert.equal(build.compatibility.dsh, manifest.engines.dsh);
assert.equal(build.compatibility.node, manifest.engines.node);
assert.deepEqual(Object.keys(build.artifacts).sort(), ['client.js', 'index.mjs']);
for (const [file, info] of Object.entries(build.artifacts)) {
  const bytes = await readFile(join(source, 'dist', file));
  assert.equal(bytes.length, info.bytes, `${file}: build size mismatch; rebuild the plugin.`);
  assert.equal(createHash('sha256').update(bytes).digest('hex'), info.sha256, `${file}: build checksum mismatch; rebuild the plugin.`);
}

await mkdir(target, { recursive: true });
await assertPermittedTree(target);
for (const file of runtimeFiles) {
  const original = join(source, file);
  assert.ok((await lstat(original)).isFile(), `${file} must be a regular file.`);
  await mkdir(dirname(join(target, file)), { recursive: true });
  await copyFile(original, join(target, file));
}
await copyFile(join(root, 'LICENSE'), join(target, 'LICENSE'));
await writeFile(join(target, 'package.json'), `${JSON.stringify(manifest, null, 2)}\n`);
// pnpm checks out the Git source using the installer's own Git configuration.
// Preserve generated bytes even on a Windows host with core.autocrlf=true.
await writeFile(join(output, '.gitattributes'), `${packagePath}/dist/** -text\n`);
await assertPermittedTree(target);
for (const file of permitted) assert.ok((await lstat(join(target, file))).isFile(), `Missing distribution file: ${file}`);

console.log(JSON.stringify({
  output, packagePath, name: manifest.name, version: manifest.version,
  compatibility: build.compatibility,
  files: [...permitted].sort(), buildVerified: true,
}, null, 2));

async function assertPermittedTree(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true, recursive: true })) {
    const filename = relative(directory, join(entry.parentPath, entry.name)).replaceAll('\\', '/');
    if (entry.isDirectory() && filename === 'dist') continue;
    assert.ok(entry.isFile() && permitted.has(filename), `Unexpected distribution entry: ${filename}`);
  }
}
